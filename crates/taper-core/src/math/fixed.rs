//! Fixed-point exponentiation in Q64.64.
//!
//! Two primitives carry the whole price ladder:
//!
//! * [`pow_q64_signed`] — `base^n` for a signed integer `n`, by binary
//!   exponentiation. Used for the taper factor `tau^i`.
//! * [`exp2`] — `2^v` for a signed Q64.64 `v`. Used to turn a log2 price into
//!   a price.
//!
//! Both round *down* at every step. That makes them deterministic, which
//! matters far more than being close to the real-valued answer: these
//! functions do not approximate the ladder, they **define** it.

